def load(path):
    out=[]
    try:
        with open(path,encoding="utf-8") as f:
            for l in f:
                l=l.strip()
                if l: out.append(json.loads(l))
    except FileNotFoundError:
        print("WARN missing:", path)
    return out

def ex(u,a,src): return {"source":src,"messages":[{"role":"user","content":u},{"role":"assistant","content":a}]}
def clean_q(q):
    q = q.split("\n")[0]
    for p in STRIP: q = q.replace(p,"")
    return q.strip()

# loosened: split on . ! ? danda ; AND comma/newline so list_5 can fill from clause-level items
SEG = re.compile(r'[^।.!?;,\n]+')
def segments(t): return [s.strip() for s in SEG.findall(t) if len(s.split()) >= 2]
def numbered(items): return "\n".join(f"{i+1}. {s}" for i,s in enumerate(items))

gen = load(GEN_IN)
new, cnt = [], Counter()

# one_word / short from verified general factoids (auto-routed by answer length)
for q, ans in FACTS:
    if len(ans.split()) == 1:
        for instr in ONE_WORD: new.append(ex(f"{q}? {instr}", ans, "aug_oneword")); cnt["oneword"]+=1
    else:
        for instr in SHORT:    new.append(ex(f"{q}? {instr}", ans, "aug_short"));   cnt["short"]+=1

# short + numbered/list from general detailed answers
cands, short_pool = [], []
for r in gen:
    m = r.get("messages",[])
    if len(m)>=2 and m[0]["role"]=="user" and m[1]["role"]=="assistant":
        a = m[1]["content"].strip()
        if 2 <= len(a.split()) <= 6:
            short_pool.append((clean_q(m[0]["content"]), a))
        s = segments(a)
        if len(s) >= 3: cands.append((clean_q(m[0]["content"]), s))
random.shuffle(short_pool); random.shuffle(cands)

for q,a in short_pool[:CAP["short"]]:
    if q: new.append(ex(f"{q} {random.choice(SHORT)}", a, "aug_short")); cnt["short"]+=1

for q,s in cands:
    if not q: continue
    if   cnt["list3"] < CAP["list3"] and len(s) >= 3:
        new.append(ex(f"{q} {LIST3}", numbered(s[:3]), "aug_list3")); cnt["list3"]+=1
    elif cnt["list5"] < CAP["list5"] and len(s) >= 5:
        new.append(ex(f"{q} {LIST5}", numbered(s[:5]), "aug_list5")); cnt["list5"]+=1
    elif cnt["numbered"] < CAP["numbered"] and len(s) >= 3:
        k = min(len(s), random.choice([3,4,5,6]))
        new.append(ex(f"{q} {random.choice(NUMBERED)}", numbered(s[:k]), "aug_numbered")); cnt["numbered"]+=1
    if all(cnt[k] >= CAP[k] for k in ("list3","list5","numbered")): break

random.shuffle(new)
allrows = gen + new
random.shuffle(allrows)
with open(OUT,"w",encoding="utf-8") as f:
    for r in allrows: f.write(json.dumps(r,ensure_ascii=False)+"\n")
print("new targeted:", dict(cnt), "| total new:", len(new))
print(f"base general: {len(gen)} -> {OUT}: {len(allrows)}")
